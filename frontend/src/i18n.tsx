type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string; pick: (o?: { vi?: string; en?: string } | null) => string };
const I18nContext = createContext<Ctx>({ lang: "vi", setLang: () => {}, t: (k) => k, pick: () => "" });

function initialLang(): Lang {
  try {
    const v = localStorage.getItem("df.lang");
    if (v === "vi" || v === "en") return v;
  } catch {
    /* storage unavailable */
  }
  return "vi";
}

// Number display follows the UI language (vi: 7,2 · en: 7.2). Kept here (not in components/ui) to avoid an import cycle.
let _numberLocale = "vi-VN";
export const numberLocale = () => _numberLocale;

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  _numberLocale = lang === "en" ? "en-US" : "vi-VN";   // read by the number formatters during this render
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("df.lang", l);
    } catch {
      /* ignore */
    }
    document.documentElement.lang = l;
  };
  const t = (k: string) => {
    const e = DICT[k];
    return e ? e[lang === "vi" ? 0 : 1] : k;
  };
  const pick = (o?: { vi?: string; en?: string } | null) => (o ? (lang === "vi" ? o.vi : o.en) || o.en || o.vi || "" : "");
  return <I18nContext.Provider value={{ lang, setLang, t, pick }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
